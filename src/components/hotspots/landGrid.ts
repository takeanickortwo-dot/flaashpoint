/** Cell size in the map viewBox (960×480). */
export const CELL = 10;
export const MAP_W = LAND_COLS * CELL;
export const MAP_H = LAND_ROWS * CELL;

export interface MapPoint {
  x: number;
  y: number;
}

/** Precomputed land-dot centers in viewBox coordinates. */
export const LAND_DOTS: MapPoint[] = (() => {
  const dots: MapPoint[] = [];
  for (let r = 0; r < LAND_ROWS; r++) {
    const row = LAND_GRID[r];
    for (let c = 0; c < LAND_COLS; c++) {
      if (row.charCodeAt(c) === 49 /* '1' */) {
        dots.push({ x: (c + 0.5) * CELL, y: (r + 0.5) * CELL });
      }
    }
  }
  return dots;
})();

/** Equirectangular projection: lat/lng → viewBox point. */
export function project(lat: number, lng: number): MapPoint {
  return {
    x: ((lng + 180) / 360) * MAP_W,
    y: ((90 - lat) / 180) * MAP_H,
  };
}
